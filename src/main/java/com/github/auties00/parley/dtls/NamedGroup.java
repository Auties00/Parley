package com.github.auties00.parley.dtls;

import javax.crypto.KeyAgreement;
import java.math.BigInteger;
import java.security.AlgorithmParameters;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.KeyPair;
import java.security.KeyPairGenerator;
import java.security.PublicKey;
import java.security.SecureRandom;
import java.security.interfaces.ECPublicKey;
import java.security.interfaces.XECPublicKey;
import java.security.spec.ECGenParameterSpec;
import java.security.spec.ECParameterSpec;
import java.security.spec.ECPoint;
import java.security.spec.ECPublicKeySpec;
import java.security.spec.NamedParameterSpec;
import java.security.spec.XECPublicKeySpec;
import java.util.Arrays;
import java.util.Optional;

/// The ECDHE groups this library negotiates, in its order of preference, with the encoding of their public keys.
///
/// X25519 keys travel as the 32-byte little-endian u-coordinate; the NIST curves as uncompressed points
/// (`0x04 || x || y`), the only format RFC 8422 and RFC 8446 allow.
///
/// @spec https://www.rfc-editor.org/rfc/rfc8422.html RFC 8422: Elliptic Curve Cryptography (ECC) Cipher Suites for Transport Layer Security (TLS) Versions 1.2 and Earlier
/// @spec https://www.rfc-editor.org/rfc/rfc7748.html RFC 7748: Elliptic Curves for Security
/// @spec https://www.rfc-editor.org/rfc/rfc8446.html RFC 8446: The Transport Layer Security (TLS) Protocol Version 1.3
enum NamedGroup {
    /// `x25519` (29).
    X25519(29, "X25519", 32),

    /// `secp256r1` (23).
    SECP256R1(23, "secp256r1", 32),

    /// `secp384r1` (24).
    SECP384R1(24, "secp384r1", 48);

    /// The source of key pairs.
    private static final SecureRandom RANDOM = new SecureRandom();

    /// The IANA code.
    private final int id;

    /// The JDK curve name.
    private final String curve;

    /// The coordinate length in bytes.
    private final int coordinateLength;

    /// Creates a group constant.
    NamedGroup(int id, String curve, int coordinateLength) {
        this.id = id;
        this.curve = curve;
        this.coordinateLength = coordinateLength;
    }

    /// {@return the group with an IANA code, or an empty optional for one this library does not implement}
    ///
    /// @param id the code
    static Optional<NamedGroup> ofId(int id) {
        for (var group : values()) {
            if (group.id == id) {
                return Optional.of(group);
            }
        }
        return Optional.empty();
    }

    /// {@return the IANA code}
    int id() {
        return id;
    }

    /// {@return a fresh ephemeral key pair}
    ///
    /// @throws DtlsException if the JDK cannot generate it
    KeyPair generate() throws DtlsException {
        try {
            if (this == X25519) {
                var generator = KeyPairGenerator.getInstance("XDH");
                generator.initialize(NamedParameterSpec.X25519, RANDOM);
                return generator.generateKeyPair();
            }
            var generator = KeyPairGenerator.getInstance("EC");
            generator.initialize(new ECGenParameterSpec(curve), RANDOM);
            return generator.generateKeyPair();
        } catch (GeneralSecurityException exception) {
            throw new DtlsException(DtlsAlert.INTERNAL_ERROR, false, "cannot generate a " + this + " key", exception);
        }
    }

    /// {@return the wire encoding of a public key of this group}
    ///
    /// @param key the key, generated by [#generate()]
    byte[] encode(PublicKey key) {
        if (this == X25519) {
            var u = ((XECPublicKey) key).getU();
            var bigEndian = unsigned(u, 32);
            var littleEndian = new byte[32];
            for (var index = 0; index < 32; index++) {
                littleEndian[index] = bigEndian[31 - index];
            }
            return littleEndian;
        }
        var point = ((ECPublicKey) key).getW();
        var encoded = new byte[1 + 2 * coordinateLength];
        encoded[0] = 4;
        System.arraycopy(unsigned(point.getAffineX(), coordinateLength), 0, encoded, 1, coordinateLength);
        System.arraycopy(unsigned(point.getAffineY(), coordinateLength), 0, encoded, 1 + coordinateLength, coordinateLength);
        return encoded;
    }

    /// {@return the public key a peer sent}
    ///
    /// @param encoded the wire encoding
    /// @throws DtlsException if the encoding is malformed or the point is not on the curve
    PublicKey decode(byte[] encoded) throws DtlsException {
        try {
            if (this == X25519) {
                if (encoded.length != 32) {
                    throw new DtlsException(DtlsAlert.ILLEGAL_PARAMETER, "X25519 key share of " + encoded.length + " bytes");
                }
                var bigEndian = new byte[32];
                for (var index = 0; index < 32; index++) {
                    bigEndian[index] = encoded[31 - index];
                }
                bigEndian[0] &= 0x7F;
                return KeyFactory.getInstance("XDH")
                        .generatePublic(new XECPublicKeySpec(NamedParameterSpec.X25519, new BigInteger(1, bigEndian)));
            }
            if (encoded.length != 1 + 2 * coordinateLength || encoded[0] != 4) {
                throw new DtlsException(DtlsAlert.ILLEGAL_PARAMETER, "malformed " + this + " point");
            }
            var x = new BigInteger(1, Arrays.copyOfRange(encoded, 1, 1 + coordinateLength));
            var y = new BigInteger(1, Arrays.copyOfRange(encoded, 1 + coordinateLength, encoded.length));
            var parameters = AlgorithmParameters.getInstance("EC");
            parameters.init(new ECGenParameterSpec(curve));
            var spec = parameters.getParameterSpec(ECParameterSpec.class);
            return KeyFactory.getInstance("EC").generatePublic(new ECPublicKeySpec(new ECPoint(x, y), spec));
        } catch (GeneralSecurityException | IllegalArgumentException exception) {
            throw new DtlsException(DtlsAlert.ILLEGAL_PARAMETER, false, "invalid " + this + " key share", exception);
        }
    }

    /// {@return the shared secret of an ECDHE exchange}
    ///
    /// @param own  this side's key pair
    /// @param peer the peer's public key
    /// @throws DtlsException if the agreement fails, including an all-zero X25519 result
    byte[] agree(KeyPair own, PublicKey peer) throws DtlsException {
        try {
            var agreement = KeyAgreement.getInstance(this == X25519 ? "XDH" : "ECDH");
            agreement.init(own.getPrivate());
            agreement.doPhase(peer, true);
            var secret = agreement.generateSecret();
            var zero = 0;
            for (var value : secret) {
                zero |= value;
            }
            if (zero == 0) {
                throw new DtlsException(DtlsAlert.ILLEGAL_PARAMETER, "all-zero ECDHE shared secret");
            }
            return secret;
        } catch (GeneralSecurityException exception) {
            throw new DtlsException(DtlsAlert.ILLEGAL_PARAMETER, false, "ECDHE key agreement failed", exception);
        }
    }

    /// {@return a non-negative integer as exactly `length` big-endian bytes}
    private static byte[] unsigned(BigInteger value, int length) {
        var bytes = value.toByteArray();
        var result = new byte[length];
        var start = Math.max(0, bytes.length - length);
        var count = bytes.length - start;
        System.arraycopy(bytes, start, result, length - count, count);
        return result;
    }
}
